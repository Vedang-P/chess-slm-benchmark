"""Analyze the representation pilot: which prompt representation do SLMs
understand best? Reads results/chess summaries from the pilot run and writes
docs/representation-pilot.md with a recommendation.

Usage:
    python scripts/run_suite.py --config configs/pilot.yaml   # (on Kaggle)
    python scripts/analyze_pilot.py                           # this script
"""
from __future__ import annotations

import glob
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

RESULTS = Path("results/chess")
VARIANT_ORDER = ["grid", "fen", "bitboard", "list"]
TASKS = ["cap-legal-8x8", "bestmove-8x8", "mate1-lichess"]


def _fmt(x):
    return "—" if x is None else f"{x * 100:.1f}%"


def main() -> None:
    runs = {}
    for p in sorted(glob.glob(str(RESULTS / "*.summary.json"))):
        s = json.loads(Path(p).read_text())
        meta = s["meta"]
        if meta["task"] not in TASKS:
            continue
        key = (meta["model"], meta["task"], meta["prompt_variant"])
        runs[key] = s

    if not runs:
        print("no pilot summaries found — run the pilot first")
        sys.exit(1)

    models = sorted({k[0] for k in runs})
    lines = [
        "# Representation Pilot",
        "",
        "Auto-generated by `scripts/analyze_pilot.py` — determines which prompt",
        "representation small models actually understand before the full sweep.",
        "",
        f"Models: {', '.join(models)}. Tasks: {', '.join(TASKS)}.",
        "",
    ]

    # per-variant aggregate across tasks and models
    lines.append("## Aggregate by representation")
    lines.append("")
    lines.append("| variant | parse | legal | compliance |")
    lines.append("|---|---|---|---|")
    agg = {}
    for v in VARIANT_ORDER:
        cells = [runs[k] for k in runs if k[2] == v]
        if not cells:
            continue
        p = [c["metrics"]["conditions"]["win"]["parse_rate"] for c in cells]
        l = [c["metrics"]["conditions"]["win"]["legal_rate"] for c in cells]
        comp = [c["metrics"]["conditions"]["win"]["compliance_of_legal"] for c in cells
                if c["metrics"]["conditions"]["win"]["compliance_of_legal"] is not None]
        mean = lambda xs: sum(xs) / len(xs) if xs else None
        agg[v] = mean(comp)
        lines.append(f"| {v} | {_fmt(mean(p))} | {_fmt(mean(l))} | {_fmt(mean(comp))} |")
    lines.append("")

    # per-task, per-variant legal rate
    lines.append("## Legal-move rate by task × representation (avg over models)")
    lines.append("")
    lines.append("| task | grid | fen | bitboard | list |")
    lines.append("|---|---|---|---|---|")
    for task in TASKS:
        row = [task]
        for v in VARIANT_ORDER:
            vals = [runs[(m, task, v)]["metrics"]["conditions"]["win"]["legal_rate"]
                    for m in models if (m, task, v) in runs]
            row.append(_fmt(sum(vals) / len(vals) if vals else None))
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")

    # recommendation
    if agg:
        winner = max(agg, key=lambda k: agg[k] if agg[k] is not None else -1)
        sorted_v = sorted(agg, key=lambda k: agg[k] if agg[k] is not None else -1, reverse=True)
        top2 = sorted_v[:2]
        lines += [
            "## Recommendation",
            "",
            f"- **Primary representation: `{winner}`** (best average compliance).",
            f"- **Secondary (paper ablation): `{', '.join(top2)}`**.",
            "- The full sweep should use the primary + secondary variants on the "
            "8x8 tasks; the remaining representations are dropped.",
            "- If compliance is near-zero for ALL variants, the failure is "
            "capability, not representation.",
            "",
        ]
    else:
        lines.append("## Recommendation\n\nInsufficient data.\n")

    (Path("docs") / "representation-pilot.md").write_text("\n".join(lines) + "\n")
    print(f"wrote docs/representation-pilot.md ({len(runs)} runs)")


if __name__ == "__main__":
    main()
