"""Analyze chess benchmark results: capability report + anti-goal report.

Reads results/chess/*.summary.json + *samples.jsonl and writes:
    docs/capability-analysis.md     (Phase 0: what can SLMs do at all?)
    docs/anti-goal-analysis.md      (Phase 1: win/lose compliance + divergence)

Usage:
    python scripts/analyze_results.py [--results-dir results/chess]
"""
from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))


def _load(results_dir: Path):
    runs = {}
    for summary_path in sorted(glob.glob(str(results_dir / "*.summary.json"))):
        s = json.loads(Path(summary_path).read_text())
        meta = s["meta"]
        key = (meta["model"], meta["task"], meta["prompt_variant"])
        runs[key] = s
    return runs


def _fmt(x):
    return "—" if x is None else f"{x:.1%}" if isinstance(x, float) else str(x)


def capability_report(runs) -> str:
    lines = [
        "# Capability Analysis: SLM chess ability (Phase 0)",
        "",
        "Auto-generated by `scripts/analyze_results.py` — raw data in `results/chess/`.",
        "",
        "## What can SLMs do at all?",
        "",
        "- `cap-legal-8x8`: make ANY legal move on standard 8x8 positions (parse + legality only).",
        "- `mate1-lichess`: solve real mate-in-1 puzzles (WIN condition).",
        "- `sm-3x3-win` / `sm-5x5-win`: play a game-theoretically winning move on solved positions.",
        "",
        "## Legality (cap-legal-8x8, by prompt variant)",
        "",
        "| model | variant | n | parse | legal |",
        "|---|---|---|---|---|",
    ]
    for (model, task, variant), s in sorted(runs.items()):
        if task != "cap-legal-8x8":
            continue
        c = s["metrics"]["conditions"]["win"]
        lines.append(f"| {model} | {variant} | {c['n']} | {_fmt(c['parse_rate'])} | {_fmt(c['legal_rate'])} |")
    lines += [
        "",
        "## Mate-in-1 solve rate (mate1-lichess, by prompt variant)",
        "",
        "| model | variant | n | parse | legal | compliance (mate found) |",
        "|---|---|---|---|---|---|",
    ]
    for (model, task, variant), s in sorted(runs.items()):
        if task != "mate1-lichess":
            continue
        c = s["metrics"]["conditions"]["win"]
        lines.append(f"| {model} | {variant} | {c['n']} | {_fmt(c['parse_rate'])} | "
                     f"{_fmt(c['legal_rate'])} | {_fmt(c['compliance_of_legal'])} |")
    lines += [
        "",
        "## Exact win-move rate (sm-3x3-win / sm-5x5-win)",
        "",
        "| model | task | n | parse | legal | compliance (winning move) |",
        "|---|---|---|---|---|---|",
    ]
    for (model, task, variant), s in sorted(runs.items()):
        if task not in ("sm-3x3-win", "sm-5x5-win"):
            continue
        c = s["metrics"]["conditions"]["win"]
        lines.append(f"| {model} | {task} | {c['n']} | {_fmt(c['parse_rate'])} | "
                     f"{_fmt(c['legal_rate'])} | {_fmt(c['compliance_of_legal'])} |")
    lines += [
        "",
        "## Reading the results",
        "",
        "- A model with high parse but low legal rate knows chess notation but not the rules.",
        "- A model with low parse on `fen` but higher on `grid` is representation-bound "
        "(or vice versa) — this directly informs which prompt representation the "
        "anti-goal study should use.",
        "- Mate-in-1 compliance near zero with legal rate > 0 means the model plays "
        "legal chess but cannot find tactics.",
    ]
    return "\n".join(lines) + "\n"


def anti_goal_report(runs) -> str:
    lines = [
        "# Anti-Goal Analysis: win/lose compliance (Phase 1)",
        "",
        "Auto-generated by `scripts/analyze_results.py` — raw data in `results/chess/`.",
        "",
        "## Compliance by task and condition",
        "",
        "| model | task | variant | cond | n | parse | legal | compliance |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for (model, task, variant), s in sorted(runs.items()):
        if task in ("cap-legal-8x8", "mate1-lichess") and "lose" not in s["metrics"]["conditions"]:
            if task == "mate1-lichess":
                continue  # covered by capability report for win; lose condition below
        for cond, c in s["metrics"]["conditions"].items():
            lines.append(f"| {model} | {task} | {variant} | {cond} | {c['n']} | "
                         f"{_fmt(c['parse_rate'])} | {_fmt(c['legal_rate'])} | "
                         f"{_fmt(c['compliance_of_legal'])} |")
    lines += [
        "",
        "## Within-model divergence (win vs lose on identical positions)",
        "",
        "| model | task | variant | divergence |",
        "|---|---|---|---|",
    ]
    for (model, task, variant), s in sorted(runs.items()):
        div = s["metrics"].get("divergence_rate")
        if div is not None:
            lines.append(f"| {model} | {task} | {variant} | {_fmt(div)} |")
    lines += [
        "",
        "## Reading the results",
        "",
        "- `divergence` near 0: the model plays the same move under WIN and LOSE "
        "instructions — the anti-goal is ignored (latent objective wins).",
        "- Compliance on LOSE above zero while WIN compliance is also positive: the "
        "model follows the objective direction (it can do both).",
        "- Both near zero with high legality: the model plays legal-but-random chess "
        "and follows neither objective.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default="results/chess")
    args = ap.parse_args()
    results_dir = Path(args.results_dir)
    runs = _load(results_dir)
    if not runs:
        print(f"no summaries found in {results_dir} — run scripts/run_suite.py first")
        sys.exit(1)
    docs = Path("docs")
    docs.mkdir(exist_ok=True)
    (docs / "capability-analysis.md").write_text(capability_report(runs))
    (docs / "anti-goal-analysis.md").write_text(anti_goal_report(runs))
    print(f"wrote docs/capability-analysis.md + docs/anti-goal-analysis.md "
          f"({len(runs)} runs)")


if __name__ == "__main__":
    main()
