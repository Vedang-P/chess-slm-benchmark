"""Analyze chess benchmark results: SLM chess capability report.

Reads results/chess/*.summary.json + writes:
    docs/capability-analysis.md     (the paper's capability tables)

Random-legal baselines come from the oracle data (expected compliance of
uniform-random legal play) and are printed for context.

Usage:
    python scripts/analyze_results.py [--results-dir results/chess]
"""
from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

DATA_DIR = Path("data/positions")


def _load(results_dir: Path):
    runs = {}
    for summary_path in sorted(glob.glob(str(results_dir / "*.summary.json"))):
        s = json.loads(Path(summary_path).read_text())
        meta = s["meta"]
        key = (meta["model"], meta["task"], meta["prompt_variant"])
        runs[key] = s
    return runs


def _fmt(x):
    return "—" if x is None else f"{x:.1%}" if isinstance(x, float) else str(x)


def _get(runs, model, task, variant):
    return runs.get((model, task, variant))


def _models(runs):
    return sorted({k[0] for k in runs})


def _win_metric(runs, model, task, variant, field="compliance_of_legal"):
    s = _get(runs, model, task, variant)
    if not s:
        return None
    c = s["metrics"].get("conditions", {}).get("win")
    return c.get(field) if c else None


def _legal(runs, model, task, variant):
    return _win_metric(runs, model, task, variant, "legal_rate")


def _game_metric(runs, model, task, field):
    s = _get(runs, model, task, "grid")
    if not s:
        return None
    g = s["metrics"].get("games")
    return g.get(field) if g else None


def capability_report(runs) -> str:
    models = _models(runs)
    lines = [
        "# Capability Analysis: SLM chess ability",
        "",
        "Auto-generated by `scripts/analyze_results.py` — raw data in `results/chess/`.",
        "",
        "Models: " + ", ".join(models) + ".",
        "",
    ]

    def section(title, header, row_fn):
        lines.append(f"## {title}")
        lines.append("")
        lines.append(header)
        lines.append("|---" * (header.count("|") - 1) + "|")
        for m in models:
            lines.append(row_fn(m))
        lines.append("")

    # 1. Legality
    section(
        "1. Legality on standard positions (cap-legal-8x8)",
        "| model | grid: parse | grid: legal | fen: parse | fen: legal |",
        lambda m: f"| {m} | {_fmt(_win_metric(runs, m, 'cap-legal-8x8', 'grid', 'parse_rate'))} | "
                  f"{_fmt(_legal(runs, m, 'cap-legal-8x8', 'grid'))} | "
                  f"{_fmt(_win_metric(runs, m, 'cap-legal-8x8', 'fen', 'parse_rate'))} | "
                  f"{_fmt(_legal(runs, m, 'cap-legal-8x8', 'fen'))} |",
    )

    # 2. Tactics
    section(
        "2. Tactics (lichess puzzles)",
        "| model | mate1: grid | mate1: fen | mate2: grid | mate2: fen |",
        lambda m: f"| {m} | {_fmt(_win_metric(runs, m, 'mate1-lichess', 'grid'))} | "
                  f"{_fmt(_win_metric(runs, m, 'mate1-lichess', 'fen'))} | "
                  f"{_fmt(_win_metric(runs, m, 'mate2-lichess', 'grid'))} | "
                  f"{_fmt(_win_metric(runs, m, 'mate2-lichess', 'fen'))} |",
    )

    # 3. Move strength vs Stockfish
    section(
        "3. Best-move accuracy vs Stockfish (bestmove-8x8)",
        "| model | grid: legal | grid: top-1 | fen: legal | fen: top-1 |",
        lambda m: f"| {m} | {_fmt(_legal(runs, m, 'bestmove-8x8', 'grid'))} | "
                  f"{_fmt(_win_metric(runs, m, 'bestmove-8x8', 'grid'))} | "
                  f"{_fmt(_legal(runs, m, 'bestmove-8x8', 'fen'))} | "
                  f"{_fmt(_win_metric(runs, m, 'bestmove-8x8', 'fen'))} |",
    )

    # 4. Exact endgames
    section(
        "4. Exact small-board endgames (retrograde oracles)",
        "| model | 3x3 win-move | 5x5 win-move | 5x5 draw->win |",
        lambda m: f"| {m} | {_fmt(_win_metric(runs, m, 'sm-3x3-win', 'grid'))} | "
                  f"{_fmt(_win_metric(runs, m, 'sm-5x5-win', 'grid'))} | "
                  f"{_fmt(_win_metric(runs, m, 'sm-5x5-draw', 'grid'))} |",
    )

    # 5. Full games
    lines.append("## 5. Full-game playout (model vs random opponent)")
    lines.append("")
    lines.append("| model | 5x5 chess: legal | 5x5 chess: win | 5x5 chess: complete | "
                 "ttt: legal | ttt: win | c4: legal | c4: win |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for m in models:
        lines.append(
            f"| {m} | {_fmt(_game_metric(runs, m, 'playout-5x5', 'legal_rate'))} | "
            f"{_fmt(_game_metric(runs, m, 'playout-5x5', 'win_rate'))} | "
            f"{_fmt(_game_metric(runs, m, 'playout-5x5', 'completion_rate'))} | "
            f"{_fmt(_game_metric(runs, m, 'ttt', 'legal_rate'))} | "
            f"{_fmt(_game_metric(runs, m, 'ttt', 'win_rate'))} | "
            f"{_fmt(_game_metric(runs, m, 'c4', 'legal_rate'))} | "
            f"{_fmt(_game_metric(runs, m, 'c4', 'win_rate'))} |"
        )
    lines.append("")

    lines += [
        "## Reading the results",
        "",
        "- **Legality is the floor**: a model that can't play legal moves can't do anything else.",
        "- **FEN vs grid**: if legality or tactics change dramatically with the representation,",
        "  small models are representation-bound, not chess-ignorant.",
        "- **Best-move top-1** near zero with high legality = plays legal-but-random chess.",
        "- **Full games**: completion rate shows whether the model can sustain a game;",
        "  win rate vs a random opponent is the strongest 'can it play at all' signal.",
        "- **Cross-game** (ttt/c4): legality in a second ruleset tests rule-generalization.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default="results/chess")
    args = ap.parse_args()
    runs = _load(Path(args.results_dir))
    if not runs:
        print(f"no summaries found in {args.results_dir} — run scripts/run_suite.py first")
        sys.exit(1)
    docs = Path("docs")
    docs.mkdir(exist_ok=True)
    (docs / "capability-analysis.md").write_text(capability_report(runs))
    print(f"wrote docs/capability-analysis.md ({len(runs)} runs)")


if __name__ == "__main__":
    main()
